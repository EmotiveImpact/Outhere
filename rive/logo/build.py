"""Writes scene.rml for the animated Outhere logo.

The geometry is Outhere.logo() from the design system, weight A: on a 100 grid
the ring is 12 wide with round ends, the dot has radius 9 and sits 5 clear of
the ring ends, in a gap centred on the bottom right (45 degrees).

Run `python3 build.py` after changing anything here, then `rive . --verify`.
Times are frames at 60fps.
"""
import math

S = 4                      # 100 grid -> 400 px mark
PAD = 40                   # room for the dot's arrival and the landing ping
C = 50 * S + PAD           # artboard is 2C square, mark centred on C
R = 40 * S                 # ring radius: 50 - max(w/2, dot) - 1 = 40
W = 12 * S                 # ring width
D = 9 * S                  # dot radius
A = math.radians(45)       # gap centre, bottom right (y grows down)
DX, DY = C + R * math.cos(A), C + R * math.sin(A)
ROT = math.radians(165)    # Rive's ellipse path starts at the top; turn it to start at 75 degrees
ARC = 300 / 360            # the gap is 60 degrees, so the ring is 300
FAR = 80                   # the dot arrives from this far out along the diagonal
GLOW = 88                  # halo radius

INK, BLUE = "FFF3F5F8", "FF4F9BFF"

# Easing, as in the design system tokens
EXPO = (0.16, 1, 0.3, 1)      # --ease-out-expo
THUMB = (0.34, 1.56, 0.64, 1)  # --ease-thumb, overshoots
GLIDE = (0.22, 1, 0.36, 1)    # --ease-glide
INOUT = (0.45, 0, 0.55, 1)
OUT = (0, 0, 0.58, 1)


def kf(value, frame, ease=None):
    """A keyframe. `ease` shapes the segment that leaves it; None holds."""
    if ease == "linear":
        return f'<KeyFrameDouble value="{value:.5f}" frame="{frame}" interpolationType="linear"/>'
    if ease is None:
        return f'<KeyFrameDouble value="{value:.5f}" frame="{frame}" interpolationType="hold"/>'
    x1, y1, x2, y2 = ease
    return (f'<KeyFrameDouble value="{value:.5f}" frame="{frame}" interpolationType="cubic">'
            f'<CubicEaseInterpolator x1="{x1}" y1="{y1}" x2="{x2}" y2="{y2}"/></KeyFrameDouble>')


def prop(key, *frames):
    body = "\n".join("                    " + f for f in frames)
    return f'                <KeyedProperty propertyKey="{key}">\n{body}\n                </KeyedProperty>'


def obj(oid, label, *props):
    return (f'            <!-- {label} -->\n            <KeyedObject objectId="{oid}">\n'
            + "\n".join(props) + "\n            </KeyedObject>")


X, Y, ROTATION, SX, SY, OPACITY, TRIM_END = 13, 14, 15, 16, 17, 18, 115

intro = "\n".join([
    obj("0:30", "ring draws on", prop(TRIM_END, kf(0, 0, EXPO), kf(ARC, 90))),
    obj("0:20", "ring sweeps round as it draws",
        prop(ROTATION, kf(ROT - math.radians(40), 0, EXPO), kf(ROT, 90)),
        prop(OPACITY, kf(0, 0, OUT), kf(1, 6))),
    obj("0:40", "dot arrives from out along the diagonal and settles in the gap",
        prop(X, kf(DX + FAR, 36, GLIDE), kf(DX, 70)),
        prop(Y, kf(DY + FAR, 36, GLIDE), kf(DY, 70)),
        prop(SX, kf(0.3, 0), kf(0.3, 36, THUMB), kf(1, 76)),
        prop(SY, kf(0.3, 0), kf(0.3, 36, THUMB), kf(1, 76)),
        prop(OPACITY, kf(0, 0), kf(0, 36, OUT), kf(1, 46))),
    obj("0:50", "glow blooms on landing, then settles",
        prop(OPACITY, kf(0, 0), kf(0, 60, OUT), kf(1, 76, INOUT), kf(0.7, 132)),
        prop(SX, kf(0.55, 0), kf(0.55, 60, OUT), kf(1.3, 80, INOUT), kf(1, 132)),
        prop(SY, kf(0.55, 0), kf(0.55, 60, OUT), kf(1.3, 80, INOUT), kf(1, 132))),
    obj("0:70", "tell the app the dot has landed",
        '                <KeyedProperty propertyKey="395">\n                    <KeyFrameCallback frame="66"/>\n                </KeyedProperty>'),
    obj("0:60", "ping ring on landing",
        prop(SX, kf(1, 0), kf(1, 66, OUT), kf(2.6, 114)),
        prop(SY, kf(1, 0), kf(1, 66, OUT), kf(2.6, 114)),
        prop(OPACITY, kf(0, 0), kf(0.7, 66, OUT), kf(0, 114))),
])

idle = "\n".join([
    obj("0:50", "glow breathes",
        prop(OPACITY, kf(0.7, 0, INOUT), kf(1, 84, INOUT), kf(0.7, 168)),
        prop(SX, kf(1, 0, INOUT), kf(1.15, 84, INOUT), kf(1, 168)),
        prop(SY, kf(1, 0, INOUT), kf(1.15, 84, INOUT), kf(1, 168))),
    obj("0:40", "dot breathes, barely",
        prop(SX, kf(1, 0, INOUT), kf(1.04, 84, INOUT), kf(1, 168)),
        prop(SY, kf(1, 0, INOUT), kf(1.04, 84, INOUT), kf(1, 168))),
])

rml = f'''<Rive version="1" kind="fragment">
    <!-- Generated by build.py. Edit that, not this. -->
    <Artboard defaultStateMachineId="0:7" styleId="0:5" width="{2 * C}" height="{2 * C}" name="Logo" id="0:2">
        <LayoutComponentStyle name="Artboard Style" id="0:5"/>
        <!-- No background: the mark sits on whatever screen it is placed on. -->
        <!-- Fired when the dot lands, so the app can play a light haptic. -->
        <Event name="landed" id="0:70"/>

        <!-- First declared paints on top: dot, glow, ping, ring. -->
        <Shape x="{DX:.3f}" y="{DY:.3f}" name="Dot" id="0:40">
            <Ellipse width="{2 * D}" height="{2 * D}" originX="0.5" originY="0.5" name="Path"/>
            <Fill name="Fill"><SolidColor colorValue="{BLUE}" name="Color"/></Fill>
        </Shape>
        <Shape x="{DX:.3f}" y="{DY:.3f}" opacity="0.7" name="Dot Glow" id="0:50">
            <Ellipse width="{2 * GLOW}" height="{2 * GLOW}" originX="0.5" originY="0.5" name="Path"/>
            <Fill name="Glow">
                <RadialGradient startX="0" startY="0" endX="{GLOW}" endY="0" name="Halo">
                    <GradientStop colorValue="CC4F9BFF" position="0"/>
                    <GradientStop colorValue="8C4F9BFF" position="0.41"/>
                    <GradientStop colorValue="2E4F9BFF" position="0.66"/>
                    <GradientStop colorValue="004F9BFF" position="1"/>
                </RadialGradient>
            </Fill>
        </Shape>
        <Shape x="{DX:.3f}" y="{DY:.3f}" opacity="0" name="Ping" id="0:60">
            <Ellipse width="{2 * D}" height="{2 * D}" originX="0.5" originY="0.5" name="Path"/>
            <Stroke thickness="3" name="Stroke"><SolidColor colorValue="{BLUE}" name="Color"/></Stroke>
        </Shape>
        <Shape x="{C}" y="{C}" rotation="{ROT:.6f}" name="Ring" id="0:20">
            <Ellipse width="{2 * R}" height="{2 * R}" originX="0.5" originY="0.5" name="Path"/>
            <Stroke thickness="{W}" cap="round" join="round" name="Stroke">
                <SolidColor colorValue="{INK}" name="Color"/>
                <TrimPath start="0" end="{ARC:.6f}" offset="0" name="Draw" id="0:30"/>
            </Stroke>
        </Shape>

        <!-- Intro plays once, then Idle loops. -->
        <StateMachine name="Logo" id="0:7">
            <StateMachineLayer name="Main" id="0:8">
                <EntryState x="0" y="0"><StateTransition stateToId="0:12"/></EntryState>
                <AnimationState x="200" y="0" animationId="0:10" id="0:12">
                    <StateTransition stateToId="0:13" enableExitTime="true" exitTimeIsPercetange="true" exitTime="100"/>
                </AnimationState>
                <AnimationState x="400" y="0" animationId="0:11" id="0:13"/>
            </StateMachineLayer>
        </StateMachine>

        <LinearAnimation loopValue="oneShot" duration="132" name="Intro" id="0:10">
{intro}
        </LinearAnimation>
        <LinearAnimation loopValue="loop" duration="168" name="Idle" id="0:11">
{idle}
        </LinearAnimation>
    </Artboard>
</Rive>
'''

if __name__ == "__main__":
    import pathlib
    pathlib.Path(__file__).with_name("scene.rml").write_text(rml)
